--Total Seats
	SELECT 
	DISTINCT COUNT (Parliament_Constituency) AS Total_Seats
	FROM constituencywise_results

--What is the total number of seats available for elections in each state.

select s.state as state_name, count(cr.parliament_constituency) as Total_Seats
from constituencywise_results cr 
inner join statewise_results sr ON cr.parliament_constituency = sr.parliament_constituency
inner join states s ON sr.state_ID = s.state_ID group by s.state

